//! cargo-aiv — auto-generate a Kani proof harness from an AI-generated Rust fn.
//!
//! Reads a single-fn `.rs` file, parses the signature with `syn`, maps each
//! parameter type to a symbolic input, and emits `<fn> + #[kani::proof] harness`.
//! Property: panic-freedom + integer overflow, bounded (Vec len <= 3, unwind 5).
//!
//!   cargo-aiv <file.rs>            # print fn + generated harness (feed to `cargo kani`)
//!
//! This is the Rust port of the Python prototype — the real product core.

use quote::quote;
use std::fs;

const HELPER: &str = r#"// auto-generated by cargo-aiv
fn any_bounded_vec<T: kani::Arbitrary>(bound: usize) -> Vec<T> {
    let len: usize = kani::any();
    kani::assume(len <= bound);
    let mut v: Vec<T> = Vec::with_capacity(len);
    for _ in 0..len { v.push(kani::any()); }
    v
}"#;

const SCALARS: &[&str] = &[
    "i8", "i16", "i32", "i64", "isize", "u8", "u16", "u32", "u64", "usize", "bool",
];

/// Decompose a path type into (base ident, generic type args), e.g. Vec<i32> -> ("Vec", [i32]).
fn path_head(ty: &syn::Type) -> Option<(String, Vec<syn::Type>)> {
    if let syn::Type::Path(tp) = ty {
        if let Some(seg) = tp.path.segments.last() {
            let mut args = Vec::new();
            if let syn::PathArguments::AngleBracketed(ab) = &seg.arguments {
                for a in &ab.args {
                    if let syn::GenericArgument::Type(t) = a {
                        args.push(t.clone());
                    }
                }
            }
            return Some((seg.ident.to_string(), args));
        }
    }
    None
}

fn is_scalar_int(ty: &syn::Type) -> Option<String> {
    let (base, args) = path_head(ty)?;
    if args.is_empty() && SCALARS.contains(&base.as_str()) {
        Some(base)
    } else {
        None
    }
}

/// Map a parameter to a symbolic-input line. Returns None if the type is unsupported.
fn map_input(name: &str, ty: &syn::Type) -> Option<String> {
    if let Some(scalar) = is_scalar_int(ty) {
        return Some(format!("    let {name}: {scalar} = kani::any();"));
    }
    let (base, args) = path_head(ty)?;
    match (base.as_str(), args.as_slice()) {
        ("Vec", [inner]) => {
            let et = is_scalar_int(inner)?; // only Vec of scalar ints in v0
            Some(format!("    let {name}: Vec<{et}> = any_bounded_vec::<{et}>(3);"))
        }
        ("Option", [inner]) => {
            is_scalar_int(inner)?;
            let tystr = quote!(#ty).to_string().replace(' ', "");
            Some(format!("    let {name}: {tystr} = kani::any();"))
        }
        _ => None,
    }
}

fn main() {
    let path = std::env::args().nth(1).unwrap_or_else(|| {
        eprintln!("usage: cargo-aiv <file.rs>");
        std::process::exit(2);
    });
    let src = fs::read_to_string(&path).expect("cannot read file");
    let file = syn::parse_file(&src).expect("parse error");
    let func = file
        .items
        .iter()
        .find_map(|it| if let syn::Item::Fn(f) = it { Some(f) } else { None })
        .expect("no top-level function found");

    let name = func.sig.ident.to_string();
    let mut inputs = Vec::new();
    let mut args = Vec::new();
    let mut supported = true;

    for arg in &func.sig.inputs {
        if let syn::FnArg::Typed(pt) = arg {
            let pname = match &*pt.pat {
                syn::Pat::Ident(pi) => pi.ident.to_string(),
                _ => {
                    supported = false;
                    continue;
                }
            };
            args.push(pname.clone());
            match map_input(&pname, &pt.ty) {
                Some(line) => inputs.push(line),
                None => {
                    supported = false;
                    let tystr = quote!(#pt).to_string();
                    inputs.push(format!("    // UNSUPPORTED: {tystr}"));
                }
            }
        }
    }

    if !supported {
        eprintln!("// cargo-aiv: `{name}` uses an unsupported type — cannot verify (v0 scope: scalar ints, Vec<int>, Option<int>).");
        std::process::exit(1);
    }

    // Emit: helper + original fn + generated harness.
    println!("{HELPER}\n");
    println!("{}\n", src.trim());
    println!("#[kani::proof]\n#[kani::unwind(5)]\nfn verify_{name}() {{");
    for l in &inputs {
        println!("{l}");
    }
    println!("    let _ = {name}({});", args.join(", "));
    println!("}}");
}
